import { x402Client, wrapFetchWithPayment } from '@x402/fetch';
import { registerExactEvmScheme } from '@x402/evm/exact/client';
import { privateKeyToAccount } from 'viem/accounts';
const k = process.env.EVM_PRIVATE_KEY; const account = privateKeyToAccount(k.startsWith('0x')?k:'0x'+k);
const client = x402Client.fromConfig({ schemes: [], spendControls: { maxAmountPerPayment: '$0.10', allowedAssets: [{ network:'eip155:11155111', asset:'0xcc194e1a843B658526D0D5C431f670028582Ae17', maxAmountPerPayment:'100000' }] } });
registerExactEvmScheme(client, { signer: account, networks: ['eip155:11155111'] });
const f = wrapFetchWithPayment(fetch, client);
const body = JSON.parse(process.argv[2]);
const r = await f(process.env.TELEGRAPH_BASE_URL + (process.argv[3]||'/engine/v1/ask'), { method:'POST', headers:{'content-type':'application/json'}, body: JSON.stringify(body) });
console.log(r.status);
for (const [h,v] of r.headers) if (/telegraph|payment|receipt|signal|x-/i.test(h)) console.log(h+':', v.slice(0,300));
console.log((await r.text()).slice(0,2500));
